CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  date_of_birth DATE,
  country_code CHAR(2),
  kyc_status TEXT NOT NULL DEFAULT 'not_started' CHECK (kyc_status IN ('not_started','pending','verified','rejected','expired')),
  account_status TEXT NOT NULL DEFAULT 'active' CHECK (account_status IN ('active','suspended','closed')),
  role TEXT NOT NULL DEFAULT 'player' CHECK (role IN ('player','admin','compliance')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'player' CHECK (role IN ('player','admin','compliance'));

CREATE TABLE IF NOT EXISTS market_rules (
  country_code CHAR(2) PRIMARY KEY,
  country_name TEXT NOT NULL,
  permitted BOOLEAN NOT NULL DEFAULT FALSE,
  license_reference TEXT,
  regulator TEXT,
  legal_reviewed_at TIMESTAMPTZ,
  kyc_required BOOLEAN NOT NULL DEFAULT TRUE,
  min_age SMALLINT NOT NULL DEFAULT 18 CHECK (min_age >= 18),
  real_money_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  notes TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (NOT real_money_enabled OR (permitted AND license_reference IS NOT NULL AND legal_reviewed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS payment_providers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  provider_key TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,
  country_code CHAR(2) NOT NULL REFERENCES market_rules(country_code),
  currency CHAR(3) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  approved_for_gambling BOOLEAN NOT NULL DEFAULT FALSE,
  credentials_secret_ref TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (NOT enabled OR approved_for_gambling)
);

CREATE TABLE IF NOT EXISTS wallets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id),
  currency CHAR(3) NOT NULL,
  balance_minor BIGINT NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(user_id, currency)
);

-- Immutable ledger: balance changes must be represented by entries, never direct client writes.
CREATE TABLE IF NOT EXISTS wallet_ledger (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_id UUID NOT NULL REFERENCES wallets(id),
  entry_type TEXT NOT NULL CHECK (entry_type IN ('deposit','withdrawal','bet_debit','bet_payout','refund','adjustment')),
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  direction SMALLINT NOT NULL CHECK (direction IN (-1,1)),
  reference TEXT NOT NULL,
  idempotency_key TEXT UNIQUE NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS game_rounds (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  server_seed_hash CHAR(64) NOT NULL,
  server_seed_encrypted TEXT,
  client_seed TEXT NOT NULL,
  nonce BIGINT NOT NULL CHECK (nonce >= 0),
  crash_point NUMERIC(12,2) NOT NULL CHECK (crash_point >= 1.00),
  status TEXT NOT NULL CHECK (status IN ('committed','running','settled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  settled_at TIMESTAMPTZ,
  UNIQUE(client_seed, nonce)
);

CREATE TABLE IF NOT EXISTS bets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  round_id UUID NOT NULL REFERENCES game_rounds(id),
  user_id UUID NOT NULL REFERENCES users(id),
  currency CHAR(3) NOT NULL,
  stake_minor BIGINT NOT NULL CHECK (stake_minor > 0),
  cashout_multiplier NUMERIC(12,2),
  payout_minor BIGINT NOT NULL DEFAULT 0 CHECK (payout_minor >= 0),
  status TEXT NOT NULL CHECK (status IN ('placed','cashed_out','lost','refunded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  settled_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS audit_log (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_user_id UUID REFERENCES users(id),
  action TEXT NOT NULL,
  subject_type TEXT NOT NULL,
  subject_id TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_users_country ON users(country_code);
CREATE INDEX IF NOT EXISTS idx_ledger_wallet_created ON wallet_ledger(wallet_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bets_user_created ON bets(user_id, created_at DESC);

-- Responsible-play controls; values are stored per account and currency.
CREATE TABLE IF NOT EXISTS responsible_play_limits (
  user_id UUID PRIMARY KEY REFERENCES users(id),
  daily_deposit_limit_minor BIGINT CHECK (daily_deposit_limit_minor >= 0),
  weekly_deposit_limit_minor BIGINT CHECK (weekly_deposit_limit_minor >= 0),
  monthly_deposit_limit_minor BIGINT CHECK (monthly_deposit_limit_minor >= 0),
  daily_loss_limit_minor BIGINT CHECK (daily_loss_limit_minor >= 0),
  session_time_limit_minutes INTEGER CHECK (session_time_limit_minutes >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS self_exclusions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id),
  starts_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ends_at TIMESTAMPTZ,
  permanent BOOLEAN NOT NULL DEFAULT FALSE,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (permanent OR ends_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS self_exclusions_user_active_idx ON self_exclusions(user_id, ends_at);

